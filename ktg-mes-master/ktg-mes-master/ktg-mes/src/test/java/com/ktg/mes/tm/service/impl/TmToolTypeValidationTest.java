package com.ktg.mes.tm.service.impl;

import com.fasterxml.jackson.databind.JsonMappingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.ktg.common.exception.ServiceException;
import com.ktg.framework.web.exception.GlobalExceptionHandler;
import com.ktg.mes.tm.controller.TmToolTypeController;
import com.ktg.mes.tm.domain.TmToolType;
import com.ktg.mes.tm.mapper.TmToolTypeMapper;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mybatis.spring.SqlSessionFactoryBean;
import org.mybatis.spring.SqlSessionTemplate;
import org.springframework.core.io.ClassPathResource;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.test.util.ReflectionTestUtils;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.MvcResult;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import com.ktg.mes.tm.service.ITmToolTypeService;
import java.nio.charset.StandardCharsets;

import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.verifyNoInteractions;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.post;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.put;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import static org.junit.jupiter.api.Assertions.*;

class TmToolTypeValidationTest {
    private EmbeddedDatabase db;
    private JdbcTemplate jdbc;
    private TmToolTypeMapper mapper;
    private TmToolTypeServiceImpl service;

    @BeforeEach
    void setUp() throws Exception {
        db = new EmbeddedDatabaseBuilder().generateUniqueName(true)
                .setType(EmbeddedDatabaseType.H2).build();
        jdbc = new JdbcTemplate(db);
        jdbc.execute("create table tm_tool_type ("
                + "tool_type_id bigint generated by default as identity primary key,"
                + "tool_type_code varchar(64), tool_type_name varchar(100), code_flag varchar(4),"
                + "mainten_type varchar(20), mainten_period int, remark varchar(255),"
                + "attr1 varchar(255), attr2 varchar(255), attr3 bigint, attr4 bigint,"
                + "create_by varchar(64), create_time timestamp, update_by varchar(64), update_time timestamp)");

        SqlSessionFactoryBean factory = new SqlSessionFactoryBean();
        factory.setDataSource(db);
        factory.setTypeAliasesPackage("com.ktg.mes.tm.domain");
        factory.setMapperLocations(new ClassPathResource("mapper/tm/TmToolTypeMapper.xml"));
        mapper = new SqlSessionTemplate(factory.getObject()).getMapper(TmToolTypeMapper.class);
        service = new TmToolTypeServiceImpl();
        ReflectionTestUtils.setField(service, "tmToolTypeMapper", mapper);
    }

    @AfterEach
    void tearDown() {
        if (db != null) db.shutdown();
    }

    @Test
    void jsonNumberWithFractionIsRejectedInsteadOfBeingTruncated() {
        JsonMappingException error = assertThrows(JsonMappingException.class,
                () -> new ObjectMapper().readValue(jsonWithPeriod("1.5"), TmToolType.class));

        assertTrue(error.getOriginalMessage().contains("保养周期"));
    }

    @Test
    void decimalStringAndLongOverflowAreRejectedWithChineseValidationMessage() {
        ObjectMapper objectMapper = new ObjectMapper();
        for (String period : new String[]{"\"1.5\"", "9223372036854775808", "\" 7 \""}) {
            JsonMappingException error = assertThrows(JsonMappingException.class,
                    () -> objectMapper.readValue(jsonWithPeriod(period), TmToolType.class), period);
            assertTrue(error.getOriginalMessage().contains("保养周期"), period);
        }
    }

    @Test
    void controllerReturnsChineseErrorWithoutJacksonDetailsForFractionalPeriods() throws Exception {
        ITmToolTypeService service = mock(ITmToolTypeService.class);
        TmToolTypeController controller = new TmToolTypeController();
        ReflectionTestUtils.setField(controller, "tmToolTypeService", service);
        MockMvc mvc = MockMvcBuilders.standaloneSetup(controller)
                .setControllerAdvice(new GlobalExceptionHandler()).build();

        for (String period : new String[]{"1.5", "\"1.5\""}) {
            for (org.springframework.test.web.servlet.request.MockHttpServletRequestBuilder request
                    : new org.springframework.test.web.servlet.request.MockHttpServletRequestBuilder[]{
                    post("/mes/tm/tooltype"), put("/mes/tm/tooltype")}) {
                MvcResult result = mvc.perform(request.contentType("application/json")
                                .content(jsonWithPeriod(period)))
                        .andExpect(status().isOk())
                        .andReturn();
                String body = result.getResponse().getContentAsString(StandardCharsets.UTF_8);
                String message = new ObjectMapper().readTree(body).path("msg").asText();
                assertTrue(message.contains("保养周期"), message);
                assertFalse(body.contains("com.fasterxml.jackson"), body);
                assertFalse(body.contains("JsonMappingException"), body);
            }
        }
        verifyNoInteractions(service);
    }

    @Test
    void controllerRejectsPeriodAboveDatabaseRangeWithoutWritingIt() throws Exception {
        TmToolTypeController controller = new TmToolTypeController();
        ReflectionTestUtils.setField(controller, "tmToolTypeService", service);
        MockMvc mvc = MockMvcBuilders.standaloneSetup(controller)
                .setControllerAdvice(new GlobalExceptionHandler()).build();
        String json = jsonWithPeriod("2147483648");

        MvcResult result = mvc.perform(post("/mes/tm/tooltype").contentType("application/json").content(json))
                .andExpect(status().isOk())
                .andReturn();

        String body = result.getResponse().getContentAsString(StandardCharsets.UTF_8);
        String message = new ObjectMapper().readTree(body).path("msg").asText();
        assertTrue(message.contains("2147483647"), message);
        assertFalse(body.contains("Exception"), body);
        assertEquals(0, countRows());
    }

    @Test
    void yRequiresSupportedMaintenanceTypeAndPositiveDatabaseIntegerPeriod() {
        String[] invalidTypes = {null, "", " ", "OTHER", "regular", "USAGE ", "REGULAR;USAGE"};
        for (String type : invalidTypes) {
            TmToolType request = request("Y", type, 1L);
            assertThrows(ServiceException.class, () -> service.insertTmToolType(request), String.valueOf(type));
        }

        Long[] invalidPeriods = {null, 0L, -1L, 2147483648L};
        for (Long period : invalidPeriods) {
            TmToolType request = request("Y", "REGULAR", period);
            assertThrows(ServiceException.class, () -> service.insertTmToolType(request), String.valueOf(period));
        }

        assertEquals(0, countRows());
    }

    @Test
    void yUpdateRejectsEveryMissingOrInvalidMaintenanceValueWithoutChangingStoredRow() {
        TmToolType original = request("Y", "REGULAR", 9L);
        assertEquals(1, service.insertTmToolType(original));

        String[] invalidTypes = {null, "", " ", "OTHER", "regular", "USAGE ", "REGULAR;USAGE"};
        for (String type : invalidTypes) {
            TmToolType update = request("Y", type, 10L);
            update.setToolTypeId(original.getToolTypeId());
            assertThrows(ServiceException.class, () -> service.updateTmToolType(update), String.valueOf(type));
        }

        Long[] invalidPeriods = {null, 0L, -1L, 2147483648L};
        for (Long period : invalidPeriods) {
            TmToolType update = request("Y", "REGULAR", period);
            update.setToolTypeId(original.getToolTypeId());
            assertThrows(ServiceException.class, () -> service.updateTmToolType(update), String.valueOf(period));
        }

        for (String codeFlag : new String[]{null, "", "X", "y"}) {
            TmToolType update = request(codeFlag, "REGULAR", 10L);
            update.setToolTypeId(original.getToolTypeId());
            assertThrows(ServiceException.class, () -> service.updateTmToolType(update), String.valueOf(codeFlag));
        }

        TmToolType saved = mapper.selectTmToolTypeByToolTypeId(original.getToolTypeId());
        assertEquals("REGULAR", saved.getMaintenType());
        assertEquals(9L, saved.getMaintenPeriod());
        assertEquals(1, countRows());
    }

    @Test
    void yAcceptsSupportedTypesAndLargestDatabaseIntegerPeriod() {
        for (String type : new String[]{"REGULAR", "USAGE"}) {
            TmToolType request = request("Y", type, 2147483647L);
            assertEquals(1, service.insertTmToolType(request));
            TmToolType saved = mapper.selectTmToolTypeByToolTypeId(request.getToolTypeId());
            assertEquals(type, saved.getMaintenType());
            assertEquals(2147483647L, saved.getMaintenPeriod());
        }
    }

    @Test
    void nClearsInapplicableFieldsOnInsertAndPersistsClearingOnUpdate() {
        TmToolType create = request("N", "USAGE", 10L);
        assertEquals(1, service.insertTmToolType(create));
        assertNormalizedOff(create.getToolTypeId());

        TmToolType update = request("Y", "REGULAR", 7L);
        update.setToolTypeId(create.getToolTypeId());
        assertEquals(1, service.updateTmToolType(update));
        TmToolType enabled = mapper.selectTmToolTypeByToolTypeId(create.getToolTypeId());
        assertEquals("REGULAR", enabled.getMaintenType());
        assertEquals(7L, enabled.getMaintenPeriod());

        update.setCodeFlag("N");
        update.setMaintenType("USAGE");
        update.setMaintenPeriod(10L);
        assertEquals(1, service.updateTmToolType(update));
        assertNormalizedOff(create.getToolTypeId());
    }

    @Test
    void yUpdateWithMissingPeriodFailsAndDoesNotReportSuccessfulStaleValue() {
        TmToolType create = request("Y", "REGULAR", 7L);
        assertEquals(1, service.insertTmToolType(create));

        TmToolType update = request("Y", "REGULAR", null);
        update.setToolTypeId(create.getToolTypeId());
        assertThrows(ServiceException.class, () -> service.updateTmToolType(update));

        TmToolType saved = mapper.selectTmToolTypeByToolTypeId(create.getToolTypeId());
        assertEquals(7L, saved.getMaintenPeriod());
        assertEquals(1, countRows());
    }

    @Test
    void nullOrUnknownCodeFlagIsRejected() {
        for (String codeFlag : new String[]{null, "", "X", "y"}) {
            assertThrows(ServiceException.class,
                    () -> service.insertTmToolType(request(codeFlag, "REGULAR", 1L)), String.valueOf(codeFlag));
        }
        assertEquals(0, countRows());
    }

    private TmToolType request(String codeFlag, String maintenanceType, Long period) {
        TmToolType request = new TmToolType();
        request.setToolTypeCode("T09-" + System.nanoTime());
        request.setToolTypeName("T09 test type");
        request.setCodeFlag(codeFlag);
        request.setMaintenType(maintenanceType);
        request.setMaintenPeriod(period);
        return request;
    }

    private String jsonWithPeriod(String periodJson) {
        return "{\"toolTypeCode\":\"T09-test\",\"toolTypeName\":\"T09 test\","
                + "\"codeFlag\":\"Y\",\"maintenType\":\"REGULAR\","
                + "\"maintenPeriod\":" + periodJson + "}";
    }

    private int countRows() {
        return jdbc.queryForObject("select count(*) from tm_tool_type", Integer.class);
    }

    private void assertNormalizedOff(Long id) {
        TmToolType saved = mapper.selectTmToolTypeByToolTypeId(id);
        assertNotNull(saved);
        assertEquals("N", saved.getCodeFlag());
        assertNull(saved.getMaintenType());
        assertNull(saved.getMaintenPeriod());
    }
}
