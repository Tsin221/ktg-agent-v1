package com.ktg.mes.dv.service.impl;

import com.ktg.common.constant.HttpStatus;
import com.ktg.common.constant.UserConstants;
import com.ktg.common.core.domain.AjaxResult;
import com.ktg.mes.dv.controller.DvCheckPlanController;
import com.ktg.mes.dv.domain.DvCheckPlan;
import com.ktg.mes.dv.mapper.DvCheckPlanMapper;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mybatis.spring.SqlSessionFactoryBean;
import org.mybatis.spring.SqlSessionTemplate;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.test.util.ReflectionTestUtils;

import static org.junit.jupiter.api.Assertions.assertEquals;

class DvCheckPlanCodeValidationTest {
    private EmbeddedDatabase db;
    private JdbcTemplate jdbc;
    private DvCheckPlanServiceImpl service;
    private DvCheckPlanController controller;

    @BeforeEach
    void setUp() throws Exception {
        db = new EmbeddedDatabaseBuilder().generateUniqueName(true).setType(EmbeddedDatabaseType.H2).build();
        jdbc = new JdbcTemplate(db);
        jdbc.execute("create table dv_check_plan (plan_id bigint generated by default as identity primary key, " +
                "plan_code varchar(64), plan_name varchar(100), plan_type varchar(20), start_date date, end_date date, " +
                "cycle_type varchar(20), cycle_count bigint, status varchar(20), remark varchar(255), " +
                "attr1 varchar(255), attr2 varchar(255), attr3 bigint, attr4 bigint, create_by varchar(64), " +
                "create_time timestamp, update_by varchar(64), update_time timestamp)");
        jdbc.update("insert into dv_check_plan(plan_id,plan_code,plan_name,plan_type) values (1,'CHECK-001','check plan','CHECK'), (2,'MAINT-001','maintenance plan','MAINTEN')");

        SqlSessionFactoryBean bean = new SqlSessionFactoryBean();
        bean.setDataSource(db);
        bean.setTypeAliasesPackage("com.ktg.mes.dv.domain");
        bean.setMapperLocations(new PathMatchingResourcePatternResolver()
                .getResource("classpath:mapper/dv/DvCheckPlanMapper.xml"));
        SqlSessionFactory factory = bean.getObject();
        DvCheckPlanMapper mapper = new SqlSessionTemplate(factory).getMapper(DvCheckPlanMapper.class);
        service = new DvCheckPlanServiceImpl();
        ReflectionTestUtils.setField(service, "dvCheckPlanMapper", mapper);
        controller = new DvCheckPlanController();
        ReflectionTestUtils.setField(controller, "dvCheckPlanService", service);
    }

    @AfterEach
    void tearDown() {
        if (db != null) db.shutdown();
    }

    @Test
    void addRejectsExistingCodeAcrossPlanTypesEvenWhenRequestContainsAnExistingId() {
        DvCheckPlan duplicate = plan("CHECK-001", "different name", "MAINTEN");
        duplicate.setPlanId(1L); // A client-supplied id must not turn an add into an edit.

        AjaxResult result = controller.add(duplicate);

        assertEquals(HttpStatus.ERROR, result.get("code"));
        assertEquals(2, jdbc.queryForObject("select count(*) from dv_check_plan", Integer.class));
        assertEquals(1, jdbc.queryForObject("select count(*) from dv_check_plan where plan_code='CHECK-001'", Integer.class));
    }

    @Test
    void addAllowsUnusedCodeForBothPlanTypes() {
        assertEquals(HttpStatus.SUCCESS, controller.add(plan("CHECK-NEW", "new check", "CHECK")).get("code"));
        assertEquals(HttpStatus.SUCCESS, controller.add(plan("MAINT-NEW", "new maintenance", "MAINTEN")).get("code"));
        assertEquals(4, jdbc.queryForObject("select count(*) from dv_check_plan", Integer.class));
    }

    @Test
    void editAllowsCurrentCodeButRejectsAnotherPlansCode() {
        DvCheckPlan keepCode = plan("CHECK-001", "renamed check plan", "CHECK");
        keepCode.setPlanId(1L);
        assertEquals(HttpStatus.SUCCESS, controller.edit(keepCode).get("code"));
        assertEquals("renamed check plan", jdbc.queryForObject("select plan_name from dv_check_plan where plan_id=1", String.class));

        DvCheckPlan conflict = plan("MAINT-001", "should not persist", "CHECK");
        conflict.setPlanId(1L);
        assertEquals(HttpStatus.ERROR, controller.edit(conflict).get("code"));
        assertEquals("CHECK-001", jdbc.queryForObject("select plan_code from dv_check_plan where plan_id=1", String.class));
    }

    @Test
    void historicalDuplicateCodesRemainQueryableAndAreAlwaysReportedAsConflicts() {
        jdbc.update("insert into dv_check_plan(plan_id,plan_code,plan_name,plan_type) values (3,'LEGACY-DUP','legacy one','CHECK'), (4,'LEGACY-DUP','legacy two','MAINTEN')");
        assertEquals(UserConstants.NOT_UNIQUE, service.checkPlanCodeUnique(plan("LEGACY-DUP", "new", "CHECK")));

        DvCheckPlan edit = plan("LEGACY-DUP", "legacy one renamed", "CHECK");
        edit.setPlanId(3L);
        assertEquals(UserConstants.NOT_UNIQUE, service.checkPlanCodeUnique(edit));
        assertEquals(2, jdbc.queryForObject("select count(*) from dv_check_plan where plan_code='LEGACY-DUP'", Integer.class));
    }

    private DvCheckPlan plan(String code, String name, String type) {
        DvCheckPlan plan = new DvCheckPlan();
        plan.setPlanCode(code);
        plan.setPlanName(name);
        plan.setPlanType(type);
        plan.setCycleType("DAY");
        plan.setCycleCount(1L);
        plan.setStatus("PREPARE");
        return plan;
    }
}
