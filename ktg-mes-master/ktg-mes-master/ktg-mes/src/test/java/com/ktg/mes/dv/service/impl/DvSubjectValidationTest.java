package com.ktg.mes.dv.service.impl;

import com.ktg.common.constant.UserConstants;
import com.ktg.common.exception.ServiceException;
import com.ktg.mes.dv.domain.DvCheckSubject;
import com.ktg.mes.dv.domain.DvSubject;
import com.ktg.mes.dv.mapper.DvCheckSubjectMapper;
import com.ktg.mes.dv.mapper.DvCheckPlanMapper;
import com.ktg.mes.dv.mapper.DvSubjectMapper;
import org.apache.ibatis.mapping.ResultMapping;
import org.apache.ibatis.session.SqlSessionFactory;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.mybatis.spring.SqlSessionFactoryBean;
import org.mybatis.spring.SqlSessionTemplate;
import org.springframework.core.io.support.PathMatchingResourcePatternResolver;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabase;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseBuilder;
import org.springframework.jdbc.datasource.embedded.EmbeddedDatabaseType;
import org.springframework.test.util.ReflectionTestUtils;

import java.util.Date;
import java.util.stream.Collectors;

import static org.junit.jupiter.api.Assertions.*;

class DvSubjectValidationTest {
    private EmbeddedDatabase db;
    private JdbcTemplate jdbc;
    private DvSubjectServiceImpl subjects;
    private DvCheckSubjectServiceImpl links;
    private DvCheckSubjectMapper linkMapper;

    @BeforeEach
    void setup() throws Exception {
        db = new EmbeddedDatabaseBuilder().generateUniqueName(true).setType(EmbeddedDatabaseType.H2).build();
        jdbc = new JdbcTemplate(db);
        SqlSessionFactoryBean bean = new SqlSessionFactoryBean();
        bean.setDataSource(db);
        bean.setTypeAliasesPackage("com.ktg.mes.dv.domain");
        PathMatchingResourcePatternResolver resolver = new PathMatchingResourcePatternResolver();
        bean.setMapperLocations(resolver.getResource("classpath:mapper/dv/DvSubjectMapper.xml"),
                resolver.getResource("classpath:mapper/dv/DvCheckPlanMapper.xml"),
                resolver.getResource("classpath:mapper/dv/DvCheckSubjectMapper.xml"));
        SqlSessionFactory factory = bean.getObject();
        createTable(factory, "DvSubject", "dv_subject", "subject_id");
        createTable(factory, "DvCheckSubject", "dv_check_subject", "record_id");
        jdbc.execute("create table dv_check_plan(plan_id bigint primary key,plan_code varchar(64),plan_name varchar(100),plan_type varchar(20),start_date date,end_date date,cycle_type varchar(20),cycle_count bigint,status varchar(20),remark varchar(255),attr1 varchar(255),attr2 varchar(255),attr3 bigint,attr4 bigint,create_by varchar(64),create_time timestamp,update_by varchar(64),update_time timestamp)");
        jdbc.update("insert into dv_check_plan(plan_id,plan_type,status) values (10,'CHECK','PREPARE'),(20,'MAINTEN','PREPARE')");
        SqlSessionTemplate session = new SqlSessionTemplate(factory);
        subjects = new DvSubjectServiceImpl();
        ReflectionTestUtils.setField(subjects, "dvSubjectMapper", session.getMapper(DvSubjectMapper.class));
        links = new DvCheckSubjectServiceImpl();
        linkMapper = session.getMapper(DvCheckSubjectMapper.class);
        ReflectionTestUtils.setField(links, "dvCheckSubjectMapper", linkMapper);
        ReflectionTestUtils.setField(links, "dvCheckPlanMapper", session.getMapper(DvCheckPlanMapper.class));
        addSource(1, "ONE", "CHECK", "Y");
        addSource(2, "TWO", "MAINTEN", "Y");
        addSource(3, "DISABLED", "CHECK", "N");
    }

    private void createTable(SqlSessionFactory factory, String name, String table, String id) {
        String columns = factory.getConfiguration().getResultMap("com.ktg.mes.dv.mapper." + name + "Mapper." + name + "Result")
                .getResultMappings().stream().map(m -> m.getColumn() + " " + columnType(m, id)).collect(Collectors.joining(","));
        jdbc.execute("create table " + table + " (" + columns + ")");
    }

    private String columnType(ResultMapping mapping, String id) {
        if (mapping.getColumn().equals(id)) return "bigint generated by default as identity primary key";
        if (Date.class.isAssignableFrom(mapping.getJavaType())) return "timestamp";
        if (mapping.getJavaType() == Long.class) return "bigint";
        return "varchar(255)";
    }

    private void addSource(long id, String code, String type, String enabled) {
        jdbc.update("insert into dv_subject(subject_id,subject_code,subject_name,subject_type,subject_content,subject_standard,enable_flag) values (?,?,?,?,?,?,?)",
                id, code, "original name", type, "original content", "original standard", enabled);
    }

    private DvSubject request(Long id, String code) {
        DvSubject request = new DvSubject();
        request.setSubjectId(id);
        request.setSubjectCode(code);
        return request;
    }

    private DvCheckSubject link(long planId, Long subjectId) {
        DvCheckSubject request = new DvCheckSubject();
        request.setPlanId(planId);
        request.setSubjectId(subjectId);
        request.setSubjectCode("forged code");
        request.setSubjectName("forged name");
        request.setSubjectType("forged type");
        request.setSubjectContent("forged content");
        request.setSubjectStandard("forged standard");
        return request;
    }

    @AfterEach
    void cleanup() { if (db != null) db.shutdown(); }

    @Test
    void newUnusedCodeIsAllowed() {
        assertEquals(UserConstants.UNIQUE, subjects.checkSubjectCodeUnique(request(null, "NEW")));
    }

    @Test
    void newDuplicateCodeIsRejected() {
        assertEquals(UserConstants.NOT_UNIQUE, subjects.checkSubjectCodeUnique(request(null, "ONE")));
    }

    @Test
    void editOwnCodeIsAllowedButAnotherRecordsCodeIsRejected() {
        assertEquals(UserConstants.UNIQUE, subjects.checkSubjectCodeUnique(request(1L, "ONE")));
        assertEquals(UserConstants.NOT_UNIQUE, subjects.checkSubjectCodeUnique(request(1L, "TWO")));
    }

    @Test
    void existingDuplicateRowsDoNotCrashAndConflictIsNotHiddenBySelf() {
        addSource(4, "ONE", "CHECK", "Y");
        assertEquals(UserConstants.NOT_UNIQUE, subjects.checkSubjectCodeUnique(request(null, "ONE")));
        assertEquals(UserConstants.NOT_UNIQUE, subjects.checkSubjectCodeUnique(request(1L, "ONE")));
        assertEquals(UserConstants.NOT_UNIQUE, subjects.checkSubjectCodeUnique(request(4L, "ONE")));
    }

    @Test
    void disabledOrMissingSourceAndWrongPlanTypeCannotBeAdded() {
        for (DvCheckSubject request : new DvCheckSubject[]{link(10, 3L), link(10, 999L), link(10, null), link(10, 2L), link(999, 1L)}) {
            assertThrows(ServiceException.class, () -> links.insertDvCheckSubject(request));
        }
        assertEquals(0, jdbc.queryForObject("select count(*) from dv_check_subject", Integer.class));
    }

    @Test
    void validCheckAndMaintenanceLinksCopyAuthoritativeSourceSnapshots() {
        for (DvCheckSubject request : new DvCheckSubject[]{link(10, 1L), link(20, 2L)}) {
            assertEquals(1, links.insertDvCheckSubject(request));
            DvCheckSubject saved = linkMapper.selectDvCheckSubjectByRecordId(request.getRecordId());
            assertEquals(request.getSubjectId() == 1L ? "ONE" : "TWO", saved.getSubjectCode());
            assertEquals("original name", saved.getSubjectName());
            assertEquals(request.getSubjectId() == 1L ? "CHECK" : "MAINTEN", saved.getSubjectType());
            assertEquals("original content", saved.getSubjectContent());
            assertEquals("original standard", saved.getSubjectStandard());
            assertNotNull(saved.getRecordId());
            assertEquals(0L, saved.getAttr3());
            assertEquals("", saved.getRemark());
        }
    }

    @Test
    void existingSnapshotsRemainReadableAfterSourceChangedOrDisabled() {
        jdbc.update("insert into dv_check_subject(record_id,plan_id,subject_id,subject_name,subject_content,subject_standard) values (90,10,1,'old name','old content','old standard')");
        jdbc.update("update dv_subject set subject_name='new name',subject_type='MAINTEN',enable_flag='N' where subject_id=1");
        DvCheckSubject saved = linkMapper.selectDvCheckSubjectByRecordId(90L);
        assertEquals("old name", saved.getSubjectName());
        assertEquals("old content", saved.getSubjectContent());
        assertEquals("old standard", saved.getSubjectStandard());
    }
}
